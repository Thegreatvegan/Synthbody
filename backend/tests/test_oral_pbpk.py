@pytest.fixture(scope="module")
def validation():
    return run_oral_pbpk_validation()


def test_validation_split_is_out_of_sample(validation):
    """Evaluated subjects must not be calibration subjects. Non-negotiable."""
    calibration = set(validation.calibration_subject_ids)
    held_out = set(validation.held_out_subject_ids)
    assert calibration and held_out
    assert not (calibration & held_out), "calibration and held-out subjects overlap"
    assert set(CALIBRATION_SUBJECT_IDS) == calibration


def test_validation_uses_the_prespecified_permeability(validation):
    """The headline must not be the best value found after looking."""
    assert validation.inputs["peff_cm_per_s"] == PRESPECIFIED_PEFF_CM_PER_S
    assert validation.inputs["prespecified"] is True


def test_validation_never_fits_the_volume_of_distribution(validation):
    """The claim that Vss is predicted rather than fitted, enforced.

    Every held-out subject must receive the physicochemistry-derived Vss, and
    it must differ from the empirically fitted value -- if the two were equal,
    the volume would have been smuggled in from the fit.
    """
    assert validation.comparison_to_empirical_model["pbpk_calibrated_parameter_count"] == 1
    fitted = FIXTURE["comparison_to_empirical_model"].get(
        "empirical_fitted_v_per_kg", 0.4588180115843965
    )
    for prediction in validation.predictions:
        assert prediction.predicted_vss_L_per_kg != pytest.approx(fitted, rel=1e-6)
        # Poulin-Theil for theophylline lands near total body water.
        assert 0.3 < prediction.predicted_vss_L_per_kg < 0.7


def test_validation_predictions_cover_every_held_out_subject(validation):
    assert len(validation.predictions) == len(validation.held_out_subject_ids)
    for prediction in validation.predictions:
        assert len(prediction.predicted_mg_per_L) == len(prediction.observed_mg_per_L)
        assert prediction.mass_balance_relative_error < 1e-9


def test_validation_is_deterministic():
    """Same protocol, same numbers. No seeds, no sampling, no drift."""
    a = run_oral_pbpk_validation()
    b = run_oral_pbpk_validation()
    assert a.pointwise_metrics == b.pointwise_metrics
    assert a.metric_summary == b.metric_summary


def test_validation_reports_achieved_accuracy(validation):
    """Pins the measured result so a later change cannot move it unnoticed.

    These are the numbers quoted in VALIDATION.md and README.md -- a published
    claim about the software. The expected values are read from a fixture that
    was generated by running the protocol, never typed in by hand, so a
    transcription slip cannot turn into a false reference value.
    """
    expected = FIXTURE
    for key, value in expected["pointwise_metrics"].items():
        assert validation.pointwise_metrics[key] == pytest.approx(value, rel=1e-9), key
    for metric, summary in expected["metric_summary"].items():
        for stat, value in summary.items():
            assert validation.metric_summary[metric][stat] == pytest.approx(
                value, rel=1e-9
            ), f"{metric}.{stat}"


def test_validation_per_subject_curves_unchanged(validation):
    """Point-by-point, not just the summary statistics.

    Two different predictions can share an AAFE, so the summary alone is a weak
    guard. This compares every predicted concentration for every held-out
    subject.
    """
    expected = FIXTURE["per_subject"]
    assert {p.subject_id for p in validation.predictions} == set(expected)
    for prediction in validation.predictions:
        reference = expected[prediction.subject_id]
        np.testing.assert_allclose(
            prediction.predicted_mg_per_L,
            reference["predicted_mg_per_L"],
            rtol=1e-9,
            err_msg=f"subject {prediction.subject_id}",
        )
        assert prediction.hepatic_clint_L_per_h == pytest.approx(
            reference["hepatic_clint_L_per_h"], rel=1e-9
        )


def test_validation_beat_the_empirical_model_with_fewer_fitted_parameters(validation):
    """The specific comparative claim made in the documentation.

    The claim is narrow and worth pinning precisely because it is the sort of
    thing that is easy to overstate: the PBPK model achieved a lower AAFE than
    the empirical one-compartment model while calibrating one parameter instead
    of fitting three.
    """
    comparison = validation.comparison_to_empirical_model
    assert comparison["pbpk_calibrated_parameter_count"] == 1
    assert comparison["empirical_fitted_parameter_count"] == 3
    assert comparison["pbpk_held_out_aafe"] < comparison["empirical_held_out_aafe"]
    # And the note must keep saying it is not a like-for-like contest, because
    # the two models were given different amounts of information.
    assert "not a like-for-like" in comparison["note"].lower()


