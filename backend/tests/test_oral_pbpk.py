def test_solution_dosing_bypasses_dissolution_and_absorbs_faster():
    solid = _run(_model())
    solution = _run(_model(oral_input=_oral_input(is_solution=True)))
    # A solution has nothing to dissolve, so it must reach its peak no later.
    t_peak_solid = solid.t_h[int(np.argmax(solid.observable("plasma_concentration")))]
    t_peak_soln = solution.t_h[int(np.argmax(solution.observable("plasma_concentration")))]
    assert t_peak_soln <= t_peak_solid


