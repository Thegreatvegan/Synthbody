# ---------------------------------------------------------------- coupling
def test_absorbed_drug_enters_the_gut_compartment_first():
    """Early on, gut tissue must lead the systemic circulation.

    This is the signature of portal routing. If absorbed drug were dumped
    straight into the venous pool, arterial and venous concentrations would rise
    together with gut rather than lagging it.
    """
    model = _model()
    result = _run(model, t_end=4.0, n=241)
    gut = result.observable("C_gut")
    arterial = result.observable("arterial_blood_concentration")
    early = result.t_h < 0.5
    # Gut tissue concentration must exceed arterial blood while drug is still
    # arriving, because gut is upstream of the systemic circulation.
    assert np.all(gut[early][1:] > arterial[early][1:])


def test_liver_sees_higher_concentration_than_systemic_blood_during_absorption():
    """First pass means the liver is exposed to the portal load, not the systemic one.

    The comparison has to be made on a plasma-equivalent basis -- liver tissue
    concentration divided by its partition coefficient -- because the raw tissue
    concentration also carries the partitioning factor, and for theophylline
    Kp_liver is below 1. Comparing raw tissue against plasma would therefore
    test partitioning rather than first pass.

    The window stops at 1.5 h because this is a statement about the absorption
    phase only. Once absorption is over the liver equilibrates with the
    systemic circulation and the gradient disappears, which is correct
    behaviour, not a failure.
    """
    model = _model()
    result = _run(model, t_end=6.0, n=301)
    kp_liver = model.distribution_model.partition_coefficients["liver"]
    liver_plasma_equivalent = result.observable("C_liver") / kp_liver
    plasma = result.observable("plasma_concentration")
    window = (result.t_h > 0.2) & (result.t_h < 1.5)
    assert np.all(liver_plasma_equivalent[window] > plasma[window])


def test_gut_wall_extraction_reduces_systemic_exposure():
    """F_gut must do something, and in the right direction."""
    without = _run(_model(gut_intrinsic_clearance_L_per_h=0.0))
    with_extraction = _run(_model(gut_intrinsic_clearance_L_per_h=200.0))
    auc_without = np.trapezoid(without.observable("plasma_concentration"), without.t_h)
    auc_with = np.trapezoid(
        with_extraction.observable("plasma_concentration"), with_extraction.t_h
    )
    assert auc_with < auc_without
    # And the extraction ledger must have accumulated the difference.
    assert with_extraction.observable("gut_wall_extracted")[-1] > 0.0
    assert without.observable("gut_wall_extracted")[-1] == 0.0


