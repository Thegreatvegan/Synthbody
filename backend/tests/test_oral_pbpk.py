"""Tests for the whole-body oral PBPK model and its clinical validation.

Three things are being protected here:

1. **Delegation.** The coupled model must call the existing absorption and
   distribution right-hand sides rather than reimplementing them. Several tests
   compare its output against the standalone parents directly, so a copy-paste
   divergence would fail rather than pass quietly.
2. **The coupling.** Absorbed drug has to arrive in the gut tissue compartment
   and reach the systemic circulation only through the liver, and gut-wall
   extraction has to actually remove drug.
3. **Methodological honesty of the validation.** The protocol must stay
   out-of-sample, the volume of distribution must stay unfitted, and the
   pre-specified permeability must stay the headline.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

from synthbody.engine.analysis.pbpk_validation import (
    CALIBRATION_SUBJECT_IDS,
    PRESPECIFIED_PEFF_CM_PER_S,
    hepatic_clint_from_plasma_clearance,
    run_oral_pbpk_validation,
)
from synthbody.engine.core import simulate
from synthbody.engine.models.absorption import CompartmentalAbsorption, OralDrugInput
from synthbody.engine.models.oral_pbpk import OralPBPK
from synthbody.engine.models.pbpk import PerfusionLimitedPBPK
from synthbody.engine.physiology.partition import DrugPhysChem
from synthbody.engine.provenance import ValidationStatus

THEOPHYLLINE_PHYSCHEM = DrugPhysChem(
    log_p=-0.02, fraction_unbound_plasma=0.60, blood_plasma_ratio=0.82
)

# Generated by running the protocol, never hand-written. See
# tests/baseline/README.md for why reference numbers are produced this way.
FIXTURE = json.loads(
    (Path(__file__).parent / "baseline" / "oral_pbpk_validation.json").read_text()
)


def _oral_input(**kw) -> OralDrugInput:
    base = dict(
        intrinsic_solubility_mg_per_mL=7.36,
        effective_permeability_cm_per_s=3.0e-4,
        pka_acidic=8.81,
    )
    base.update(kw)
    return OralDrugInput(**base)


def _model(**kw) -> OralPBPK:
    base = dict(
        drug_physchem=THEOPHYLLINE_PHYSCHEM,
        oral_input=_oral_input(),
        body_weight_kg=70.0,
        hepatic_intrinsic_clearance_L_per_h=4.5,
    )
    base.update(kw)
    return OralPBPK(**base)


def _run(model: OralPBPK, dose_mg: float = 320.0, t_end: float = 30.0, n: int = 361):
    y0 = model.initial_state_for_dose(dose_mg)
    grid = np.linspace(0.0, t_end, n)
    return simulate(
        model, t_end_h=t_end, output_times_h=grid, initial_state=y0,
        check_tolerance_refinement=False,
    )


# ---------------------------------------------------------------- structure
def test_state_vector_is_the_two_parents_plus_one_ledger():
    model = _model()
    absorption = CompartmentalAbsorption(drug=_oral_input())
    distribution = PerfusionLimitedPBPK(drug=THEOPHYLLINE_PHYSCHEM)
    expected = len(absorption.state_names) + len(distribution.state_names) + 1
    assert len(model.state_names) == expected
    # The absorption block must come first and be unmodified.
    assert model.state_names[: len(absorption.state_names)] == absorption.state_names
    assert model.state_names[-1] == "A_gut_wall_extracted_mg"


def test_absorption_rhs_is_delegated_not_reimplemented():
    """The lumen derivatives must equal the standalone model's, exactly.

    If someone reimplements the dissolution maths here, this test fails on the
    first digit rather than drifting unnoticed.
    """
    model = _model()
    standalone = CompartmentalAbsorption(drug=_oral_input())
    dose = 250.0
    y = model.initial_state_for_dose(dose)
    y_abs_only = standalone.initial_state_for_dose(dose)

    # Perturb into a non-trivial state so the comparison is not of zeros.
    y[1] = 40.0
    y[3] = 25.0
    y_abs_only[1] = 40.0
    y_abs_only[3] = 25.0

    d_coupled = model.rhs(1.0, y, np.zeros_like(y))
    d_standalone = standalone.rhs(1.0, y_abs_only, np.zeros_like(y_abs_only))
    n_abs = len(standalone.state_names)
    np.testing.assert_allclose(d_coupled[:n_abs], d_standalone, rtol=0, atol=0)


def test_predicted_fabs_matches_the_standalone_absorption_model():
    """Coupling must not perturb the absorption prediction at all."""
    model = _model()
    result = _run(model)
    coupled_fabs = float(result.observable("fraction_absorbed")[-1])

    standalone = CompartmentalAbsorption(drug=_oral_input())
    y0 = standalone.initial_state_for_dose(320.0)
    grid = np.linspace(0.0, 30.0, 361)
    alone = simulate(
        standalone, t_end_h=30.0, output_times_h=grid, initial_state=y0,
        check_tolerance_refinement=False,
    )
    assert coupled_fabs == pytest.approx(
        float(alone.observable("fraction_absorbed")[-1]), rel=1e-6
    )


