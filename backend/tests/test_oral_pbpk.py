def test_renal_fraction_barely_moves_the_result():
    """The documented claim that the all-hepatic simplification is immaterial.

    Theophylline is a low-extraction drug, so moving 10% of its clearance from
    the liver to the kidney should change predicted exposure negligibly. This
    test is what makes that sentence in the module docstring checkable rather
    than merely asserted.
    """
    all_hepatic = run_oral_pbpk_validation(renal_fraction_of_clearance=0.0)
    with_renal = run_oral_pbpk_validation(renal_fraction_of_clearance=0.10)
    a = all_hepatic.pointwise_metrics["aafe"]
    b = with_renal.pointwise_metrics["aafe"]
    assert abs(a - b) < 0.01, f"renal split moved AAFE from {a} to {b}"


